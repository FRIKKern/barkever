import {browser, device, newNote, typeAtEndOf, leave, saved, synced, serverNote, everything, summary, sleep, until} from './lib.mjs'
const b = await browser()
const A = await device(b), B = await device(b)
const stamp = Date.now()
const id = await newNote(A, `Second clash ${stamp}`, 'Base.')
await leave(A); await synced(A)
await B.goto(`/?n=${id}`)
await until(async () => (await B.getByTestId('canvas').textContent())?.includes('Base.'))
await B.context().setOffline(true)
await typeAtEndOf(B, 0, ' B1.'); await leave(B); await saved(B)
await typeAtEndOf(A, 0, ' A1.'); await leave(A); await saved(A); await synced(A)
await B.context().setOffline(false); await synced(B)
await until(async () => everything(await serverNote(id)).includes('A1.'))
await sleep(1500)
console.log('after offline clash:', JSON.stringify(summary(await serverNote(id))))
await A.locator("main.editor").screenshot({path: "second-clash-1-after-offline-A.png"})
await typeAtEndOf(A, 0, ''); await typeAtEndOf(B, 0, '')
const typist = (p, w) => p.keyboard.type(Array.from({length: 8}, (_, i) => ` ${w}${i}`).join(''), {delay: 60})
await Promise.all([typist(A, 'a'), typist(B, 'b')])
await Promise.all([leave(A), leave(B)]); await Promise.all([synced(A), synced(B)]); await sleep(2000); await Promise.all([synced(A), synced(B)])
const n = await serverNote(id)
console.log('after online typing:', JSON.stringify(summary(n)))
console.log(JSON.stringify({id, offlineLoserA1Survives: everything(n).includes('A1.'), a7: everything(n).includes('a7'), b7: everything(n).includes('b7'), errors: [...A.errors, ...B.errors]}))
const inReplica = (page) => page.evaluate(async (id) => { const name = (await indexedDB.databases()).map((d) => d.name).find((n) => n?.startsWith('barkever-')); const db = await new Promise((ok) => { const r = indexedDB.open(name); r.onsuccess = () => ok(r.result) }); const n = await new Promise((ok) => { const r = db.transaction('notes').objectStore('notes').get(id); r.onsuccess = () => ok(r.result) }); db.close(); return JSON.stringify(n).includes('A1.') }, id)
console.log('A1 in replica A:', await inReplica(A), '| B:', await inReplica(B), '| A page text has A1:', (await A.locator('main.editor').innerText()).includes('A1.'))
await A.locator('main.editor').screenshot({path: 'second-clash-2-after-online-A.png'})
await b.close()
